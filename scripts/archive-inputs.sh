#!/usr/bin/env bash
# Print a deterministic fingerprint of every file that goes INTO the release
# archive.
#
# Why: the archive digest can only be reproduced when the *input set* is
# identical. The 0.2.4 and 0.2.5 failures were partly this — a pin taken from
# one tree, verified against another (a different tag commit, or a tree where
# docs had been edited after pinning). A test that only compares built bytes
# cannot tell you *why* they differ. This fingerprint can, and it can be
# compared between two commits without building anything.
#
# It is pinned alongside the artifact digests (scripts/archive-inputs.txt), so:
#
#   * the pre-tag gate, running on the release branch, and the release job,
#     running on the *tagged merge commit*, both recompute it. If the two trees
#     differ in any file the archive contains, the fingerprint differs and the
#     release fails instead of shipping bytes nobody verified. That closes the
#     "gate validated a different tree than the tag" gap.
#   * editing README.md / docs / manifest / data / shell / the staged scripts
#     after pinning is detected even if nobody rebuilds.
#
# Scope: exactly the files `scripts/package-release.sh` stages. Deliberately
# EXCLUDED, each for a reason:
#
#   scripts/daemon-checksums.txt  the archive stages a copy of it, but that copy
#                                 is derived from itself (current-version entries
#                                 dropped), so including it would be circular.
#                                 The binary digests cover the binaries; this
#                                 file's own content is covered by review.
#   bin/*, shell/omavrything/bin/*  build outputs, gitignored, not in the tree.
#                                 Their bytes are pinned by the per-binary
#                                 digests.
#   dist/, INSTALL.txt            generated by the packaging step itself.
#
# Usage:
#   scripts/archive-inputs.sh            # print "<sha256>"
#   scripts/archive-inputs.sh --list     # print the per-file hashes (debugging)
#   scripts/archive-inputs.sh --check    # compare against scripts/archive-inputs.txt
#
# --check exits 0 on a match, 1 on a mismatch (with a per-file diff), 2 when the
# pin file is missing.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$here"

# The exact staged set, in the order package-release.sh installs it. Keep this
# list in sync with that script: a file added there and not here would let a
# change slip past the freeze check.
inputs() {
  printf '%s\n' \
    LICENSE \
    README.md \
    manifest.json \
    docs/*.md \
    data/config/config.toml \
    data/dbus/tech.alatcerdas.omavrything.conf \
    data/man/omavrythingd.8 \
    data/polkit/tech.alatcerdas.omavrything.policy \
    data/systemd/omavrythingd.service \
    data/sysusers/omavrything.conf \
    data/tmpfiles/omavrything.conf \
    shell/omavrything/SearchBar.qml \
    shell/omavrything/SearchOverlay.qml \
    shell/omavrything/Service.qml \
    scripts/benchmark.sh \
    scripts/bootstrap.sh \
    scripts/doctor.sh \
    scripts/fetch-daemon.sh \
    scripts/install.sh \
    scripts/restart-all.sh \
    scripts/run-daemon.sh \
    scripts/uninstall.sh
}

# One line per input: "<mode>  <content-sha256>  <path>". Mode matters because
# install.sh stages executables 0755 and data files 0644, so an accidental mode
# change alters the archive even with identical bytes.
per_file() {
  # shellcheck disable=SC2046
  local f
  for f in $(inputs | LC_ALL=C sort); do
    [[ -f "$f" ]] || {
      echo "error: archive input is missing: $f" >&2
      exit 1
    }
    printf '%s  %s  %s\n' \
      "$(stat -c '%a' "$f")" \
      "$(sha256sum "$f" | awk '{print $1}')" \
      "$f"
  done
}

case "${1:-}" in
  --list)
    per_file
    ;;
  --check)
    pinned="scripts/archive-inputs.txt"
    if [[ ! -f "$pinned" ]]; then
      echo "error: $pinned is missing" >&2
      echo "       run scripts/checksums-add.sh after packaging to create it" >&2
      exit 2
    fi
    actual="$(per_file)"
    expected="$(grep -vE '^[[:space:]]*(#|$)' "$pinned")"
    if [[ "$actual" == "$expected" ]]; then
      echo "archive inputs match $pinned"
      exit 0
    fi
    echo "error: archive inputs changed since the pin was taken" >&2
    echo "" >&2
    echo "These files are inside the release archive. Changing any of them" >&2
    echo "changes the archive digest, so the pin no longer describes this tree." >&2
    echo "" >&2
    diff <(printf '%s\n' "$expected") <(printf '%s\n' "$actual") >&2 || true
    echo "" >&2
    echo "Fix: re-run scripts/package-release.sh && scripts/checksums-add.sh and" >&2
    echo "commit the new pin BEFORE tagging. Do not edit these files after it." >&2
    exit 1
    ;;
  "" | *)
    per_file | sha256sum | awk '{print $1}'
    ;;
esac
